        "# DEMO SCRIPT", "", f"**{NAME}**", "",
        "Generated by `python -m stp.reports.presentation_md`. Order: ML Lab, Real PRs, GitHub PR, honest verdict.", "",
        "## The 60-second pitch", "",
        "> \"When programmers change code, a server re-runs thousands of tests in a fixed order, often for hours. We "
