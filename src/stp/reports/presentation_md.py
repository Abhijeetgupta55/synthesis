"""Generate reports/RUBRIC_MAP.md and reports/DEMO_SCRIPT.md from results JSON (no number typed by hand).

DEMO_SCRIPT.md's timing section is filled from reports/results/live_demo_timing.json (live_demo/phase_c.py, run on
mains power); until that exists it says so and gives a provisional recommendation from the profile's measured
pytest start-up overhead.

Usage: python -m stp.reports.presentation_md
"""
from __future__ import annotations

import statistics

from stp import paths
from stp.reports.error_md import _ci, get, verdict
from stp.reports.fmt import HEADLINE, NAME, table
from stp.reports.results_md import _r

SHOTS = "reports/demo_screenshots"


def rubric_map() -> str:
    L, C, M, LR, RF, GB, U = (_r(n) for n in ("labels", "models_classification", "models", "tune_lr", "tune_rf",
                                              "tune_lgbm", "univariate"))
    best_pr = max(("lr", "rf", "lgbm", "vote", "stack"), key=lambda m: get(C, "models", m, "pr_auc", default=0))
    top_feat = max((U.get("features") or {}).items(), key=lambda kv: kv[1]["pr_auc"], default=("?", {"pr_auc": 0}))
    ec = C.get("error_corr") or {}
    rc = "?"
    if ec:
        n = ec["names"]
        rc = f"{ec['residual_corr'][n.index('lgbm')][n.index('rf')]:.2f}"
    rows = [
        ["1 EDA", "Label balance, suite durations, failure frequency, first-time failures, change sizes, the "
                  "paper's baselines re-run", "The ML pipeline → 1 EDA", "EDA_REPORT.md",
         f"failure rate {get(L, 'pooled', 'pos_rate_fail', default=0):.3%} per (run, test class)",
         "Rare failures and long suites decide the metric (PR-AUC) and the target (time to first failure)."],
        ["2 Feature derivation", "25 as-of features in four groups (history, cost, change, co-failure); leakage "
                                 "tests; rejected features with reasons", "→ 2 Features", "FEATURES.md",
         f"strongest single feature `{top_feat[0]}` PR-AUC {top_feat[1]['pr_auc']:.3f}",
         "Each group answers one question about the test; as-of computation keeps future results out."],
        ["3 Classification", "Logistic regression, random forest, LightGBM predict P(fail) per (run, test)",
         "→ 3 Classification", "MODELING.md §1, §4",
         f"PR-AUC LR {get(C, 'models', 'lr', 'pr_auc', default=0):.3f} / RF {get(C, 'models', 'rf', 'pr_auc', default=0):.3f}"
         f" / LightGBM {get(C, 'models', 'lgbm', 'pr_auc', default=0):.3f}",
         "A linear baseline, bagging and boosting; PR-AUC because accuracy rewards always saying 'pass'."],
        ["4 Regularization", "L1 / L2 / elastic net for LR; depth and leaf size for RF; L1, L2, subsampling and "
                             "early stopping for LightGBM", "→ 4 Regularization", "MODELING.md §3",
         f"LR {get(LR, 'best', 'penalty', default='?')} C = {get(LR, 'best', 'C', default='?')} "
         f"({get(LR, 'best', 'n_zero_coef', default='?')} coefficients zero); RF depth "
         f"{get(RF, 'best', 'max_depth', default='?')}", "Chosen on validation by the train/validation gap."],
        ["5 Hyperparameter tuning", f"Optuna TPE, {len(GB.get('trials', []))} trials, validation PR-AUC, "
                                    "time-ordered validation", "→ 5 Tuning", "MODELING.md §3",
         f"best validation PR-AUC {GB.get('best_value', 0):.3f}",
         "Validation builds come after training builds, as in real use."],
        ["6 Ensembles", "Bagging (RF) vs boosting (LightGBM); soft voting and stacking of all three",
         "→ 6 Ensembles", "MODELING.md §6",
         f"PR-AUC stacking {get(C, 'models', 'stack', 'pr_auc', default=0):.3f} vs LightGBM "
         f"{get(C, 'models', 'lgbm', 'pr_auc', default=0):.3f}; error correlation LightGBM–RF {rc}",
         "Ensembles add little because the members make the same mistakes."],
        ["7 Performance analysis", "PR-AUC, precision/recall@k, calibration, APFDc vs every baseline with "
                                   "PR-clustered CIs, error analysis, probability-floor trade-off",
         "→ 7 Performance; Results page", "MODELING.md §5, RESULTS.md §3–4",
         f"vs best simple rule, all failures {_ci(get(M, 'vs_best_simple', 'All', 'macro10', 'lgbm'))}; first-time "
         f"failures {_ci(get(M, 'vs_best_simple', 'FirstFail-old', 'macro10', 'lgbm'))}",
         "Ordering quality is what a CI user feels; CIs resample pull requests because builds of one PR correlate."],
    ]
    return "\n".join([
        "# RUBRIC MAP", "", f"**{NAME}**. {HEADLINE}", "",
        "Generated by `python -m stp.reports.presentation_md` from `reports/results/*.json`. App tabs are on the "
        "dashboard's 'The ML pipeline' page.", "",
        table(["Rubric item", "What was done", "App tab", "Report section", "Key number", "One-sentence justification"],
              rows), "", f"Best classifier by PR-AUC: {best_pr}.", ""])


def timing_section() -> tuple[list[str], str]:
    T = _r("live_demo_timing")
    prof = get(_r("real_world"), "networkx", "profile", default={}) or {}
    sess = T.get("demo_sessions") or []
    runs = [r for s in sess for r in s["runs"] if r.get("on_ac") is not False and r.get("returncode") == 0]
    if not runs:
        ov = [x for x in prof.get("overhead_s", []) if x is not None]
        prov = ("networkx/algorithms subset" if ov and min(ov) > 30 else "full suite")
        return ([
            "**Status: pending.** The live comparison has not yet been timed on mains power (the laptop was on "
            "battery; HUMAN_TODO item 0 runs `python live_demo/phase_c.py --repeats 3`). This section fills itself "
            "from `reports/results/live_demo_timing.json` when it exists.", "",
            f"Provisional recommendation: **{prov}**. pytest start-up and collection alone took "
            + (", ".join(f"{x:.0f}" for x in ov) if ov else "?") + " s per full-suite run when NetworkX was profiled, "
            "and the default lane pays that before its first test.", ""], prov)
    rows, tot = [], {}
    for variant in ("full", "subset"):
        rv = [r for r in runs if r["variant"] == variant]
        for lane in ("default", "smartci"):
            el = [r["lanes"][lane]["elapsed_s"] for r in rv if r["lanes"].get(lane, {}).get("elapsed_s")]
            ff = [r["lanes"][lane]["first_failure_after_s"] for r in rv
                  if r["lanes"].get(lane, {}).get("first_failure_after_s") is not None]
            if el:
                rows.append([variant, lane, len(el), f"{statistics.median(el):.1f}", f"{min(el):.1f}–{max(el):.1f}",
                             f"{statistics.median(ff):.2f}" if ff else "–"])
        cmd = [r["command_s"] for r in rv]
        if cmd:
            tot[variant] = statistics.median(cmd)
    rec = "subset" if tot.get("full", 1e9) > 150 and "subset" in tot else "full"
    label = {"subset": "networkx/algorithms subset", "full": "full suite"}[rec]
    return ([table(["Variant", "Lane", "Runs", "Median s (whole lane)", "Range s", "Median s to first failure"], rows),
             "", "Whole `smartci compare` command, both lanes, median: " +
             ", ".join(f"{k} {v:.0f} s" for k, v in tot.items()) + ".", "",
             f"**Recommendation: {label}** (rule: use the full suite if one command takes at most 150 s, else the "
             "subset).", ""], label)


def demo_script() -> str:
    M, RW = _r("models"), _r("real_world")
    nx = get(RW, "networkx", "backtest_summary", "all", default={})
    tsec, rec = timing_section()
    sub = "" if rec == "full suite" else ""
    pick = "scripts\\run_live_compare.ps1 -Pick 2" + (' -Subset ""' if rec == "full suite" else "")
    d = get(M, "vs_best_simple", "All", "macro10", "lgbm")
    f = get(M, "vs_best_simple", "FirstFail-old", "macro10", "lgbm")
    steps = [
        ["0:00", "Terminal: `scripts\\run_live_compare.ps1` (prints the numbered bug list), then `" + pick + "`. Leave "
                 "it running.", "Both lanes really run pytest on NetworkX: default order first, then smartci.",
         "\"While real tests run in the background, here is the problem.\"",
         f"Use the recorded result in REAL_WORLD.md, or `{SHOTS}/04_race_replay.png`."],
        ["0:15", "Browser: **Overview**.", "The race picture, the pipeline, four numbers.",
         "\"Tests run in a fixed order; the failing one is often near the end. We predict which tests fail and run "
         "them first. Nothing is skipped.\"", f"`{SHOTS}/01_overview.png`"],
        ["1:00", "**The ML pipeline** → tabs 1 to 3.", "EDA, features, classification.",
         "\"Failures are rare, so accuracy is useless; PR-AUC measures ranking.\"", f"`{SHOTS}/02_1_*.png` … `02_3_*`"],
        ["2:00", "Tabs 4 to 6.", "Regularization curves, Optuna history, ensemble error correlation.",
         "\"Ensembles add little because all models make the same mistakes.\"", f"`{SHOTS}/02_4_*` … `02_6_*`"],
        ["3:00", "Tab 7 Performance.", "APFDc vs every baseline with CIs.",
         f"\"On all failures we tie the best simple rule ({_ci(d)}); on first-time failures we lose to fastest-first "
         f"({_ci(f)}).\"", f"`{SHOTS}/02_7_7_performance.png`"],
        ["3:45", "**Predict live**: add `networkx/algorithms/shortest_paths/weighted.py`.",
         "The real model ranks all NetworkX test files now, with reasons; simple rules beside it.",
         "\"This is the real model running now, the same function as the command line.\"",
         f"`{SHOTS}/03_predict_live.png`"],
        ["4:45", "Terminal: read the `=== result ===` block.", "Elapsed and first-failure seconds, both lanes.",
         "\"Same bug, same tests: only the order differs.\"", "If the run failed: the timing table below."],
        ["5:30", "**Results**.", "Scoreboard, error analysis, floor trade-off, recommendation.",
         "\"ML wins on recurring failures, loses on first-time ones, and we can show why.\"",
         f"`{SHOTS}/05_results.png`"],
        ["6:45", "**Limits and honesty**.", "What is real, what is replayed, caveats.",
         "\"On a small repo a simple rule is enough; the model helps on long suites with recurring failures.\"",
         f"`{SHOTS}/06_limits_and_honesty.png`"],
        ["7:30", "Questions.", "VIVA_NOTES.md 'Questions this framing invites'.", "", ""],
    ]
    _ = sub
    return "\n".join([
        "# DEMO SCRIPT (7–8 minutes)", "", f"**{NAME}**", "",
        "Generated by `python -m stp.reports.presentation_md`. Audience: a professor who knows ML but not CI/CD.",
        "", "## Before the talk", "",
        "1. Laptop on mains power. Close other heavy programs.",
        "2. `scripts\\run_demo.ps1` (dashboard at http://localhost:8501). Open it once, click 'Predict live' once so "
        "the model is loaded.",
        "3. A second terminal in the repository root for the live comparison.",
        f"4. Fallbacks ready: screenshots in `{SHOTS}/`, and the text-only replay `python -m stp.demo.cli --seed 42`.",
        "", "## Minute by minute", "",
        table(["Time", "Click / type", "What appears", "Say", "If it fails"], steps), "",
        f"Key numbers to have in mind: NetworkX median seconds to first failure, default "
        f"{get(nx, 'median_ttff_s', 'default', 'median', default=0):.1f} vs smartci "
        f"{get(nx, 'median_ttff_s', 'smartci', 'median', default=0):.2f} vs changed-files-first "
        f"{get(nx, 'median_ttff_s', 'changed_files_first', 'median', default=0):.2f} ({nx.get('n')} bugs); model vs "
        f"best simple rule on all LRTS failures {_ci(d)} ({verdict(d)}).", "",
        "## Live comparison: measured timings and the recommended variant", "", *tsec,
        "## If something fails", "",
        "- **Dashboard does not start:** show the screenshots in order; every page has one.",
        "- **Live comparison hangs or errors:** stop it (Ctrl+C), say that the replay uses the same measured "
        "durations, and show 'Race replay' for the same bug.",
        "- **No browser at all:** `python -m stp.demo.cli --seed 42` prints a replay as text.",
        "- **Predict live is slow on first click:** it loads the model once (a few seconds); talk over it.", ""])


def main() -> None:
    (paths.ROOT / "reports" / "RUBRIC_MAP.md").write_text(rubric_map(), encoding="utf-8")
    (paths.ROOT / "reports" / "DEMO_SCRIPT.md").write_text(demo_script(), encoding="utf-8")
    print("wrote reports/RUBRIC_MAP.md and reports/DEMO_SCRIPT.md")


if __name__ == "__main__":
    main()
