"""Generate reports/RESULTS.md (the research story) and reports/SLIDE_NUMBERS.md from reports/results/*.json.

Usage: python -m stp.reports.results_md
"""
from __future__ import annotations

import json

from stp import paths
from stp.reports.error_md import error_analysis_md, meaning
from stp.reports.fmt import HEADLINE, NAME, QUESTION, table


def _r(name):
    f = paths.RESULTS / f"{name}.json"
    return json.loads(f.read_text(encoding="utf-8")) if f.exists() else {}


def get(d, *keys, default=None):
    for k in keys:
        if not isinstance(d, dict) or k not in d:
            return default
        d = d[k]
    return d


def slide_numbers() -> list[tuple[str, str, str]]:
    """(label, value, source) for every number the team may quote."""
    out = []

    def add(label, val, src, fmt="{:.3f}"):
        if val is None:
            return
        out.append((label, fmt.format(val) if not isinstance(val, str) else val, src))

    f = _r("phase0_facts")
    add("Runs whose previous run (same stage) had not finished at start, macro",
        get(f, "fact1", "share_prev_run_unfinished_at_start", "macro"), "phase0_facts.json", "{:.1%}")
    add("… Kafka", get(f, "fact1", "share_prev_run_unfinished_at_start", "per_project", "kafka"), "phase0_facts.json",
        "{:.1%}")
    add("'last outcome = fail' values taken from an unfinished run, macro",
        get(f, "fact1", "share_last_outcome_fail_rows_from_unfinished_run", "macro"), "phase0_facts.json", "{:.1%}")
    lb = _r("leakage_bruteforce")
    add("Brute-force leakage check (runs matching)", f"{lb.get('n_match')}/{lb.get('n_runs')}" if lb else None,
        "leakage_bruteforce.json")
    g = _r("gate2_reproduction")
    for k, v in get(g, "gate", default={}).items():
        add(f"Paper reproduction {k} (ours vs target {v['target']})", v["ours"], "gate2_reproduction.json", "{:.4f}")
        add(f"Same technique as-of {k}", v["as_of"], "gate2_reproduction.json", "{:.4f}")
    L = _r("labels")
    add("Pooled failure rate per (run, test class)", get(L, "pooled", "pos_rate_fail"), "labels.json", "{:.3%}")
    add("Accuracy of always predicting 'pass'", get(L, "pooled", "always_pass_accuracy"), "labels.json", "{:.2%}")
    c = _r("models_classification")
    for m in ("lr", "rf", "lgbm", "vote", "stack"):
        add(f"testC PR-AUC {m}", get(c, "models", m, "pr_auc"), "models_classification.json")
        add(f"testC ROC-AUC {m}", get(c, "models", m, "roc_auc"), "models_classification.json")
    M = _r("models")
    for sub, groups in get(M, "cells", default={}).items():
        best = get(M, "best_simple_by_val", sub)
        for meth in ("lgbm", "stack", best):
            ci = get(groups, "macro10", meth, "apfdc")
            if ci:
                add(f"APFDc {sub} {meth} (macro, test)", f"{ci['mean']:.3f} [{ci['lo']:.3f}, {ci['hi']:.3f}]",
                    "models.json")
        d = get(M, "vs_best_simple", sub, "macro10", "lgbm")
        if d:
            add(f"Δ APFDc {sub} lgbm − {best}", f"{d['mean']:+.3f} [{d['lo']:+.3f}, {d['hi']:+.3f}]", "models.json")
    v = get(M, "vs_cbt_lastfail_All")
    if v:
        add("Δ APFDc All lgbm − cbt_LastFail", f"{v['mean']:+.3f} [{v['lo']:+.3f}, {v['hi']:+.3f}]", "models.json")
    for k, x in get(M, "ablation_question", default={}).items():
        if isinstance(x, dict):
            add(f"Ablation {k}: Δ APFDc FirstFail-old vs best simple", f"{x['mean']:+.3f} [{x['lo']:+.3f}, {x['hi']:+.3f}]",
                "models.json")
    T = _r("transfer")
    for k, x in get(T, "variants", default={}).items():
        add(f"TVM transfer {k}: valB / testC PR-AUC", f"{x['valB_pr_auc']:.3f} / {x['testC_pr_auc']:.3f}", "transfer.json")
    rw = _r("real_world")
    for repo, x in rw.items():
        if repo.startswith("_"):
            continue
        add(f"{repo}: reproducible mined bugs", get(x, "learn", "n_kept"), "real_world.json", "{}")
        add(f"{repo}: mutants", get(x, "n_mutants"), "real_world.json", "{}")
        for kind, s in (get(x, "backtest_summary") or {}).items():
            for m in ("default", "smartci", s.get("best_simple_baseline")):
                med = get(s, "median_ttff_s", m)
                if med:
                    add(f"{repo} {kind}: median s to 1st failure, {m}", f"{med['median']:.2f} [{med['lo']:.2f}, {med['hi']:.2f}]",
                        "real_world.json")
        g5 = get(x, "gate5")
        if g5:
            add(f"{repo}: GATE 5 checks passed", f"{g5['n_pass']}/{g5['n_checks']}", "gate5_*.json")
    return out


def main() -> None:
    nums = slide_numbers()
    (paths.ROOT / "reports" / "SLIDE_NUMBERS.md").write_text(
        "# SLIDE_NUMBERS\n\nGenerated by `python -m stp.reports.results_md` from `reports/results/*.json`. Quote only "
        "these.\n\n" + table(["What", "Value", "Source"], [list(x) for x in nums]) + "\n", encoding="utf-8")
    M, g, f, T, rw = _r("models"), _r("gate2_reproduction"), _r("phase0_facts"), _r("transfer"), _r("real_world")
    best = get(M, "best_simple_by_val", default={})

    def cell(sub, m):
        x = get(M, "cells", sub, "macro10", m, "apfdc")
        return "–" if not x else f"{x['mean']:.3f} [{x['lo']:.3f}, {x['hi']:.3f}]"

    rows = [[s, best.get(s), cell(s, best.get(s)), cell(s, "lgbm"), cell(s, "stack"),
             (lambda d: "–" if not d else f"{d['mean']:+.3f} [{d['lo']:+.3f}, {d['hi']:+.3f}]")(
                 get(M, "vs_best_simple", s, "macro10", "lgbm"))]
            for s in ("All", "FirstFail-asof", "FirstFail-old", "New/Edited")]
    text = f"""# RESULTS: {NAME}

**The question.** {QUESTION}

**The answer.** {HEADLINE}

Generated by `python -m stp.reports.results_md` from `reports/results/*.json`. Details: BASELINES.md (baselines and
the leak), FEATURES.md, MODELING.md (models, tuning, ablations, transfer), REAL_WORLD.md (smartci on real repos).

## 1. Problem

CI suites in the LRTS dataset (108,366 runs, 10 Apache projects) take hours. Running the tests most likely to fail
first surfaces a failure sooner without skipping anything. The hard case is **first-time failures**: tests that have
never failed, for which "run what failed recently" cannot help.

## 2. A leak-free setup, and a leak in the paper's baselines

Every feature is **as-of**: a run only sees results of runs that had *finished* when it started (end = start +
capped build duration). The LRTS paper's history baselines use the previous run *by start time*; in
{get(f, 'fact1', 'share_prev_run_unfinished_at_start', 'macro', default=0):.1%} of runs (macro) that run was still
running, and {get(f, 'fact1', 'share_last_outcome_fail_rows_from_unfinished_run', 'macro', default=0):.1%} of
"last outcome = fail" values come from unfinished runs. We reproduce the paper's numbers within ±0.005 (GATE 2:
{'PASS' if g.get('gate_pass') else 'FAIL'}); re-running the *same* baselines as-of moves macro APFDc only slightly
(BASELINES.md §3): recent failures repeat, so losing the newest one rarely changes the ranking. The leak is real and
frequent, its effect on these baselines small. While reproducing we also found that the paper's published TVM
FirstFail numbers were computed with a different protocol than the other nine projects (WORKLOG, GATE 2).

## 3. Models

Binary classification of P(test class fails in this run) from 25 as-of features (history, cost, change relatedness,
co-failure memory), negative-sampled training, isotonic calibration on unsampled validation data, ordering by
P / expected duration. Logistic regression (elastic-net), random forest, LightGBM (Optuna), soft voting and stacking.

| Subset | Best simple baseline (chosen on val) | Its APFDc | LightGBM | Stacking | Δ LightGBM − best |
|---|---|---|---|---|---|
""" + "\n".join("| " + " | ".join(str(c) for c in r) + " |" for r in rows) + f"""

(Test split, macro over 10 projects, 95% PR-clustered bootstrap CIs.)

{meaning(M)}

TVM's pytest suites: the variant chosen by TVM validation (`{T.get('chosen')}`) failed confirmation on the TVM test
split; the shipped model is `{T.get('shipped')}` (disclosed selection; MODELING.md §7; §4.2 below explains the
collapse).

{error_analysis_md(_r("error_analysis"))}

## 5. Real repositories (smartci)

""" + "\n".join(f"- **{k}**: {get(v, 'learn', 'n_kept')} reproducible mined bugs, {get(v, 'n_mutants')} mutants; "
                f"best simple baseline (all bugs): {get(v, 'backtest_summary', 'all', 'best_simple_baseline')}; "
                f"{get(v, 'backtest_summary', 'all', 'recommendation')}" for k, v in rw.items() if not k.startswith("_")) + """

See REAL_WORLD.md for the tables, win/tie/loss, every loss, the simulation-vs-real check (GATE 5) and caveats.

## 6. Limitations

- LRTS has test-class granularity, no execution order and summed (not wall-clock) test time; wall-clock numbers are
  approximate (× median build/suite ratio, capped at 1).
- Models are evaluated at one origin (the test split); baselines also on every rolling-origin window.
- Small projects have < 30 test runs each; only their pooled macro is interpreted.
- Real-repo bugs are reintroduced known bugs or synthetic mutants (REAL_WORLD.md caveats).
- A simple rule can win; smartci reports it and recommends it when it does.
"""
    (paths.ROOT / "reports" / "RESULTS.md").write_text(text, encoding="utf-8")
    print(f"wrote reports/RESULTS.md and SLIDE_NUMBERS.md ({len(nums)} numbers)")


if __name__ == "__main__":
    main()
