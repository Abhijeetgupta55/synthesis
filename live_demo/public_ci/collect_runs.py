"""Pull the public GitHub Actions timings of the smartci-compare runs into reports/PUBLIC_RUNS.md.

    set GITHUB_TOKEN=<a read-only token>   (or GH_TOKEN; public repos also work unauthenticated, rate-limited)
    python live_demo/public_ci/collect_runs.py --repo <you>/<fork>

For every branch in live_demo/public_ci/branches.json: the latest `smartci-compare` workflow run, its two jobs
(default, smartci), each job's pytest step start/end (GitHub's own timestamps), and links to the run. Writes
reports/results/public_runs.json and reports/PUBLIC_RUNS.md.
"""
from __future__ import annotations

import argparse
import json
import os
import urllib.request
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
API = "https://api.github.com"


def get(url: str) -> dict:
    req = urllib.request.Request(url, headers={"Accept": "application/vnd.github+json"})
    tok = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")
    if tok:
        req.add_header("Authorization", f"Bearer {tok}")
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.loads(r.read().decode())


def secs(a: str | None, b: str | None) -> float | None:
    if not a or not b:
        return None
    f = "%Y-%m-%dT%H:%M:%SZ"
    return (datetime.strptime(b, f) - datetime.strptime(a, f)).total_seconds()


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True, help="owner/name of your fork")
    a = ap.parse_args()
    branches = json.loads((Path(__file__).parent / "branches.json").read_text(encoding="utf-8"))["branches"]
    rows = []
    for br, info in branches.items():
        runs = get(f"{API}/repos/{a.repo}/actions/runs?branch={br}&per_page=20")["workflow_runs"]
        runs = [r for r in runs if r["name"] == "smartci-compare"]
        if not runs:
            rows.append({"branch": br, **info, "status": "no run yet"})
            continue
        run = runs[0]
        jobs = get(run["jobs_url"])["jobs"]
        row = {"branch": br, **info, "run_url": run["html_url"], "status": run["status"],
               "conclusion": run["conclusion"]}
        for j in jobs:
            step = next((s for s in j["steps"] if s["name"].startswith("pytest")), None)
            row[f"{j['name']}_pytest_s"] = secs(step and step["started_at"], step and step["completed_at"])
            row[f"{j['name']}_job_s"] = secs(j["started_at"], j["completed_at"])
            row[f"{j['name']}_url"] = j["html_url"]
        rows.append(row)
    (ROOT / "reports" / "results" / "public_runs.json").write_text(json.dumps(rows, indent=1), encoding="utf-8")
    lines = ["# PUBLIC_RUNS", "", f"GitHub Actions runs of `smartci-compare` on `{a.repo}` (generated by "
             "`live_demo/public_ci/collect_runs.py`; timings are GitHub's own step timestamps).", "",
             "| Branch | Bug | Run | default pytest -x (s) | smartci pytest -x (s) |", "|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['branch']} | {r['kind']} {r['id'][:10]} | "
                     f"{'[run](' + r['run_url'] + ')' if r.get('run_url') else r['status']} | "
                     f"{r.get('default_pytest_s', '–')} | {r.get('smartci_pytest_s', '–')} |")
    (ROOT / "reports" / "PUBLIC_RUNS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(rows)} branches -> reports/PUBLIC_RUNS.md")


if __name__ == "__main__":
    main()
