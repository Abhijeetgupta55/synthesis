"""Pull the public GitHub Actions timings of the smartci-compare runs into reports/PUBLIC_RUNS.md.

    set GITHUB_TOKEN=<a read-only token>   (or GH_TOKEN; public repos also work unauthenticated, rate-limited)
    python live_demo/public_ci/collect_runs.py --repo <you>/<fork>

For every branch in live_demo/public_ci/branches.json: the latest `smartci-compare` workflow run, its two jobs
(default, rule, model), each job's pytest step start/end (GitHub's own timestamps), and links to the run. Writes
reports/results/public_runs.json and reports/PUBLIC_RUNS.md.
"""
from __future__ import annotations

import argparse
import json
import os
import urllib.request
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
API = "https://api.github.com"


class _NoAuthRedirect(urllib.request.HTTPRedirectHandler):
    """Artifact zips redirect to blob storage, which rejects GitHub's Authorization header: drop it there."""
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        new = super().redirect_request(req, fp, code, msg, headers, newurl)
        if new is not None:
            new.headers.pop("Authorization", None)
            new.unredirected_hdrs.pop("Authorization", None)
        return new


_OPENER = urllib.request.build_opener(_NoAuthRedirect)


def fetch(req: urllib.request.Request, tries: int = 6) -> bytes:
    """GET with retries (slow or flaky connections time out on the TLS handshake)."""
    import time
    for i in range(tries):
        try:
            with _OPENER.open(req, timeout=60) as r:
                return r.read()
        except OSError:
            if i == tries - 1:
                raise
            time.sleep(2 + 2 * i)


def get(url: str) -> dict:
    req = urllib.request.Request(url, headers={"Accept": "application/vnd.github+json"})
    tok = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")
    if tok:
        req.add_header("Authorization", f"Bearer {tok}")
    return json.loads(fetch(req).decode())


def secs(a: str | None, b: str | None) -> float | None:
    if not a or not b:
        return None
    f = "%Y-%m-%dT%H:%M:%SZ"
    return (datetime.strptime(b, f) - datetime.strptime(a, f)).total_seconds()


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True, help="owner/name of your fork")
    a = ap.parse_args()
    branches = json.loads((Path(__file__).parent / "branches.json").read_text(encoding="utf-8"))["branches"]
    rows = []
    for br, info in branches.items():
        runs = get(f"{API}/repos/{a.repo}/actions/runs?branch={br}&per_page=20")["workflow_runs"]
        runs = [r for r in runs if r["name"] == "smartci-compare" and r["status"] == "completed"]
        if not runs:
            rows.append({"branch": br, **info, "status": "no completed run yet"})
            continue
        run = runs[0]
        jobs = get(run["jobs_url"])["jobs"]
        row = {"branch": br, **info, "run_url": run["html_url"], "status": run["status"], "event": run["event"],
               "conclusion": run["conclusion"], "jobs": {}}
        for j in jobs:
            step = next((s for s in j["steps"] if s["name"].startswith("pytest")), None)
            row["jobs"][j["name"]] = {"job_s": secs(j["started_at"], j["completed_at"]), "url": j["html_url"],
                                      "pytest_step_s": secs(step and step["started_at"], step and step["completed_at"]),
                                      "conclusion": j["conclusion"]}
        row["summaries"] = summaries(a.repo, run["id"])
        rows.append(row)
    (ROOT / "reports" / "results" / "public_runs.json").write_text(json.dumps(rows, indent=1), encoding="utf-8")
    lines = ["# PUBLIC_RUNS", "", f"GitHub Actions runs of `smartci-compare` on `{a.repo}`, generated by "
             "`live_demo/public_ci/collect_runs.py`. Job and step times are GitHub's own timestamps (1 s resolution); "
             "queue position and test time come from each job's uploaded summary.", "",
             "| Branch | Bug | Run | Order | Queue position | Test s to failure | pytest step s | Whole job s |",
             "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        head = f"| {r['branch']} | [{r['kind']} {r['id'][:10]}]({r.get('url') or ''}) | " +                (f"[run]({r['run_url']})" if r.get("run_url") else r["status"])
        if not r.get("jobs"):
            lines.append(head + " | | | | | |")
            continue
        for k in ("default", "rule", "model"):
            j, s = r["jobs"].get(k, {}), (r.get("summaries") or {}).get(k, {})
            q = f"{s['queue_position']} of {s['n_test_files']}" if s.get("queue_position") else "–"
            t = s.get("test_s_to_first_failure")
            lines.append(f"{head} | {k} | {q} | {'–' if t is None else f'{t:.2f}'} | {j.get('pytest_step_s', '–')} | "
                         f"[{j.get('job_s', '–')}]({j.get('url', '')}) |")
            head = "| | |"
    (ROOT / "reports" / "PUBLIC_RUNS.md").write_text(chr(10).join(lines) + chr(10), encoding="utf-8")
    print(f"{len(rows)} branches -> reports/PUBLIC_RUNS.md")


def summaries(repo: str, run_id: int) -> dict:
    """The summary-<job> artifacts of a run (needs a token: GitHub only serves artifact zips to signed-in users)."""
    import io
    import zipfile
    if not (os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")):
        return {}
    out = {}
    for art in get(f"{API}/repos/{repo}/actions/runs/{run_id}/artifacts")["artifacts"]:
        if not art["name"].startswith("summary-"):
            continue
        req = urllib.request.Request(art["archive_download_url"], headers={
            "Authorization": f"Bearer {os.environ.get('GITHUB_TOKEN') or os.environ.get('GH_TOKEN')}"})
        z = zipfile.ZipFile(io.BytesIO(fetch(req)))
        for n in z.namelist():
            if n.startswith("summary-") and n.endswith(".json"):
                s = json.loads(z.read(n).decode())
                out[s["name"]] = s
    return out


if __name__ == "__main__":
    main()
